async function callDirectClientGemini(
  query: string,
  history: ChatMessage[],
  apiKey: string
): Promise<{ reply: string; tags?: string[]; actions?: ChatAction[] } | null> {
  try {
    const { GoogleGenAI } = await import('@google/genai');
    const ai = new GoogleGenAI({ apiKey });

    let promptText = query;
    if (Array.isArray(history) && history.length > 0) {
      const historyContext = history
        .slice(-6)
        .map((h) => `${h.sender === 'user' ? 'User' : 'Assistant'}: ${h.text}`)
        .join('\n');
      promptText = `Conversation History:\n${historyContext}\n\nCurrent User Question: ${query}`;
    }

    const response = await ai.models.generateContent({
      model: 'gemini-2.5-flash',
      contents: promptText,
      config: {
        systemInstruction: `You are the AI Architecture & Portfolio Copilot for Mohamed Shabeeth N, AI Engineer at TCS Chennai specializing in Agentic RAG, AST-verified SQL tool calling (Talk2Data), and speculative execution (SpecExec, 51.8% latency reduction). Winner of TCS AI Fridays Innovator Award 2025. Contact: mohamed.shabeeth@gmail.com. Keep answers technical, concise, and articulate.`,
        temperature: 0.7,
      },
    });

    const reply = response.text || '';
    if (reply.trim().length > 0) {
      const lowerReply = (reply + ' ' + query).toLowerCase();
      const actions: ChatAction[] = [];
      const tags: string[] = [];

      if (lowerReply.includes('specexec') || lowerReply.includes('51.8') || lowerReply.includes('latency')) {
        actions.push({ label: 'Inspect SpecExec', type: 'open_project', projectId: '02' });
        tags.push('SpecExec', '51.8% Latency Cut');
      }
      if (lowerReply.includes('talk2data') || lowerReply.includes('ast') || lowerReply.includes('sql')) {
        actions.push({ label: 'Inspect Talk2Data', type: 'open_project', projectId: '01' });
        tags.push('Talk2Data', 'AST Validation');
      }
      if (lowerReply.includes('contact') || lowerReply.includes('hire') || lowerReply.includes('consult')) {
        actions.push({ label: 'Consult With Shabeeth', type: 'open_contact' });
        tags.push('Chennai, India', 'Open for Consulting');
      }

      return {
        reply,
        tags: tags.length > 0 ? tags.slice(0, 3) : ['Gemini Flash', 'AI Engineer'],
        actions: actions.length > 0 ? actions.slice(0, 3) : [
          { label: 'Inspect SpecExec', type: 'open_project', projectId: '02' },
          { label: 'Inspect Talk2Data', type: 'open_project', projectId: '01' },
          { label: 'Consult With Me', type: 'open_contact' },
        ],
      };
    }
  } catch (err) {
    console.warn('Direct client Gemini call error:', err);
  }
  return null;
}

export async function askPortfolioAI(
  userQuery: string,
  history: ChatMessage[] = []
): Promise<{ reply: string; tags?: string[]; actions?: ChatAction[] }> {
  const query = userQuery.trim();
  if (!query) {
    return getPortfolioResponse('');
  }

  // Instant zero-latency handling for greetings and openers
  const lowerQuery = query.toLowerCase();
  const isGreeting =
    /^(hi|hello|hey|hiya|greetings|good morning|good afternoon|good evening|yo|sup|namaste|vanakkam)\b/i.test(lowerQuery) ||
    lowerQuery === 'hi' ||
    lowerQuery === 'hello' ||
    lowerQuery === 'hey';

  if (isGreeting) {
    return getPortfolioResponse(query);
  }

  // 1. First attempt: call /api/chat (works locally with server.ts and on Netlify via Netlify Functions)
  try {
    const controller = new AbortController();
    const timeoutId = setTimeout(() => controller.abort(), 9000);

    const response = await fetch('/api/chat', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        message: query,
        history: history.slice(-6).map((m) => ({ sender: m.sender, text: m.text })),
      }),
      signal: controller.signal,
    });

    clearTimeout(timeoutId);

    if (response.ok) {
      const data = await response.json();
      if (data && typeof data.reply === 'string' && data.reply.trim().length > 0) {
        return {
          reply: data.reply,
          tags: Array.isArray(data.tags) && data.tags.length > 0 ? data.tags : ['Gemini 3.8 Flash', 'AI Engineer'],
          actions: Array.isArray(data.actions) && data.actions.length > 0 ? data.actions : [
            { label: 'Inspect SpecExec', type: 'open_project', projectId: '02' },
            { label: 'Inspect Talk2Data', type: 'open_project', projectId: '01' },
            { label: 'Consult With Me', type: 'open_contact' },
          ],
        };
      }
    }
  } catch (err) {
    console.warn('/api/chat request failed or timed out, trying standalone client options:', err);
  }

  // 2. Second attempt: Direct client-side LLM call if VITE_GEMINI_API_KEY is configured in Netlify/client environment
  const clientApiKey = (import.meta as any).env?.VITE_GEMINI_API_KEY;
  if (clientApiKey && typeof clientApiKey === 'string' && clientApiKey.length > 5) {
    const directResult = await callDirectClientGemini(query, history, clientApiKey);
    if (directResult) {
      return directResult;
    }
  }

  // 3. Third tier: Instant, comprehensive local knowledge base fallback (guarantees 100% uptime without failure)
  return getPortfolioResponse(query);
}

